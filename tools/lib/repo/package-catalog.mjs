/**
 * `docs/reference/package-catalog.generated.md` 的纯逻辑扫描与渲染器。
 * 状态：常驻
 * 何时跑：改本文件或 `packages/company-pack/{package.json,cordis.patch.yml,presets/**}` 后；
 *        `npx vitest run tests/tools/package-catalog.spec.ts && pnpm gen:catalog -- --check && pnpm verify`。
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { flattenCordisRows, loadCordisYaml } from '../core/repo-markdown.mjs'

/**
 * 扫描 `packages/company-pack/` 的静态清单（package.json、cordis.patch.yml、presets）。
 * @param {string} root 仓库根目录
 */
export function scanPackageCatalog(root) {
  const packDir = join(root, 'packages/company-pack')
  const pkgPath = join(packDir, 'package.json')
  const patchPath = join(packDir, 'cordis.patch.yml')
  const presetsDir = join(packDir, 'presets')

  if (!existsSync(pkgPath)) throw new Error(`package-catalog: 缺 ${pkgPath}`)
  if (!existsSync(patchPath)) throw new Error(`package-catalog: 缺 ${patchPath}`)

  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  const exportsList = Object.entries(pkg.exports ?? {}).map(([subpath, target]) => ({
    subpath,
    target: typeof target === 'string' ? target : (target?.default ?? JSON.stringify(target)),
  }))
  const clientInject = Array.isArray(pkg.dsh?.client?.inject) ? [...pkg.dsh.client.inject] : []

  const patchOps = loadCordisYaml(readFileSync(patchPath, 'utf8')) ?? []
  const bundleRows = []
  for (const op of Array.isArray(patchOps) ? patchOps : []) {
    if (Array.isArray(op?.insert)) {
      for (const row of flattenCordisRows([op])) {
        bundleRows.push({
          mode: 'insert',
          id: String(row?.id ?? ''),
          name: String(row?.name ?? ''),
          note: row?.group === true ? 'cordis:group' : (row?.disabled === true ? 'disabled' : 'active'),
        })
      }
    } else if (op && typeof op === 'object') {
      bundleRows.push({
        mode: 'replace',
        id: String(op.id ?? ''),
        name: String(op.name ?? ''),
        note: op.disabled === true ? 'disabled' : 'override',
      })
    }
  }

  const presets = []
  if (existsSync(presetsDir)) {
    const dirs = readdirSync(presetsDir, { withFileTypes: true })
      .filter(entry => entry.isDirectory() && !entry.name.startsWith('_'))
      .map(entry => entry.name)
      .sort()
    for (const dirName of dirs) {
      const ymlPath = join(presetsDir, dirName, 'agent.cordis.yml')
      if (!existsSync(ymlPath)) continue
      const ops = loadCordisYaml(readFileSync(ymlPath, 'utf8')) ?? []
      const rows = flattenCordisRows(ops)
      const presetRow = rows.find(row => row?.name === '@deepseek-ai/dsh-agent-preset')
      const hasPersona = rows.some(row => row?.name === '@deepseek-ai/dsh-persona')
      const pluginNames = [...new Set(
        rows
          .filter(row => row?.name && row.name !== '@deepseek-ai/dsh-agent-preset' && row.name !== 'cordis:group')
          .map(row => String(row.name)),
      )].sort()
      const skillsDir = join(presetsDir, dirName, 'skills')
      const skills = existsSync(skillsDir)
        ? readdirSync(skillsDir, { withFileTypes: true })
            .filter(entry => entry.isDirectory())
            .map(entry => entry.name)
            .sort()
        : []
      presets.push({
        dir: dirName,
        id: String(presetRow?.config?.id ?? dirName),
        displayName: String(presetRow?.config?.name ?? dirName),
        hasPersona,
        skills,
        plugins: pluginNames,
      })
    }
  }

  return {
    name: String(pkg.name ?? ''),
    version: String(pkg.version ?? ''),
    dshEngine: String(pkg.engines?.dsh ?? ''),
    nodeEngine: String(pkg.engines?.node ?? ''),
    exportsList,
    clientInject,
    bundleRows,
    presets,
  }
}

/**
 * 将扫描结果渲染为确定性 Markdown（不含易漂的计数短语）。
 * @param {ReturnType<typeof scanPackageCatalog>} catalog
 */
export function renderPackageCatalog(catalog) {
  const lines = [
    '<!-- Generated by `pnpm gen:catalog -- --write`. Do not hand-edit. -->',
    '# 包与能力自动目录（`packages/company-pack/`）',
    '',
    '> 本文件由 `tools/repo/gen-catalog.mjs` 从 `package.json`、`cordis.patch.yml` 与 `presets/*/agent.cordis.yml` 自动生成，勿手改；门禁 `script-index` 校验新鲜度。',
    '',
    '## 1. 包身份与导出面',
    '',
    `- **包名**：\`${catalog.name}\`（版本 \`${catalog.version}\`）`,
    `- **引擎约束**：\`node ${catalog.nodeEngine}\` · \`dsh ${catalog.dshEngine}\``,
    '',
    '| 导出子路径 | 产物入口 |',
    '|---|---|',
    ...catalog.exportsList.map(item => `| \`${item.subpath}\` | \`${item.target}\` |`),
    '',
    '## 2. Bundle 组合行（`cordis.patch.yml`）',
    '',
    '| 方式 | 行 ID | 模块 / 插件 | 状态 |',
    '|---|---|---|---|',
    ...catalog.bundleRows.map(row => `| ${row.mode} | \`${row.id}\` | \`${row.name}\` | ${row.note} |`),
    '',
    '## 3. Preset 目录（`presets/*/agent.cordis.yml`）',
    '',
    '| 目录 / ID | 显示名 | Persona | 专属 Skills | 声明的插件包 |',
    '|---|---|---|---|---|',
    ...catalog.presets.map(preset => {
      const persona = preset.hasPersona ? `inline (\`presets/${preset.dir}/agent.cordis.yml\`)` : '—'
      const skills = preset.skills.length > 0 ? preset.skills.map(s => `\`${s}\``).join(' · ') : '—'
      const plugins = preset.plugins.map(p => `\`${p.replace(/^@deepseek-ai\/dsh-/, 'dsh-')}\``).join(', ')
      return `| \`${preset.id}\` | ${preset.displayName} | ${persona} | ${skills} | ${plugins} |`
    }),
    '',
    '## 4. Client 注入到达边（`dsh.client.inject`）',
    '',
    ...catalog.clientInject.map(mod => `- \`${mod}\``),
    '',
  ]
  return lines.join('\n')
}
