import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterAll, describe, expect, it } from 'vitest'
import { repositoryRoot as ROOT } from '../../tools/lib/core/repository-layout.mjs'
import { renderPackageCatalog, scanPackageCatalog } from '../../tools/lib/repo/package-catalog.mjs'

const tmpRoot = mkdtempSync(join(tmpdir(), 'pkg-catalog-'))
afterAll(() => { rmSync(tmpRoot, { recursive: true, force: true }) })

describe('package-catalog 自动目录扫描与渲染', () => {
  it('扫描真实 packages/company-pack 并渲染确定性 Markdown', () => {
    const catalog = scanPackageCatalog(ROOT)
    expect(catalog.name).toBe('dsh-company-pack')
    expect(catalog.exportsList.some(item => item.subpath === '.')).toBe(true)
    expect(catalog.exportsList.some(item => item.subpath === './client')).toBe(true)
    expect(catalog.bundleRows.some(row => row.id === 'company-client')).toBe(true)
    expect(catalog.presets.some(preset => preset.id === 'ceo' && preset.hasPersona)).toBe(true)
    expect(catalog.clientInject.length).toBeGreaterThan(0)

    const rendered = renderPackageCatalog(catalog)
    expect(rendered).toContain('<!-- Generated by `pnpm gen:catalog -- --write`. Do not hand-edit. -->')
    expect(rendered).toContain('## 1. 包身份与导出面')
    expect(rendered).toContain('## 2. Bundle 组合行（`cordis.patch.yml`）')
    expect(rendered).toContain('## 3. Preset 目录（`presets/*/agent.cordis.yml`）')
    expect(rendered).toContain('## 4. Client 注入到达边（`dsh.client.inject`）')
    // 不产出被 nav-count-claims 禁止的计数短语
    expect(rendered).not.toMatch(/\d+\s*个(?:页签|公司角色|preset)/)
  })

  it('缺失 package.json 或 cordis.patch.yml 时显式抛错', () => {
    const empty = join(tmpRoot, 'empty')
    mkdirSync(join(empty, 'packages/company-pack'), { recursive: true })
    expect(() => scanPackageCatalog(empty)).toThrow(/缺/)
    writeFileSync(join(empty, 'packages/company-pack/package.json'), JSON.stringify({ name: 'x', version: '0.1.0' }))
    expect(() => scanPackageCatalog(empty)).toThrow(/cordis\.patch\.yml/)
  })

  it('覆盖合成包：string 导出、replace disabled 行、无 skills/无 persona preset 与无 presets 目录分支', () => {
    const synth = join(tmpRoot, 'synth')
    mkdirSync(join(synth, 'packages/company-pack/presets/alpha'), { recursive: true })
    mkdirSync(join(synth, 'packages/company-pack/presets/_shared'), { recursive: true })
    mkdirSync(join(synth, 'packages/company-pack/presets/empty-dir'), { recursive: true })
    writeFileSync(join(synth, 'packages/company-pack/package.json'), JSON.stringify({
      name: 'synth-pack',
      version: '1.0.0',
      exports: { './raw': './raw.js', './obj': { default: './obj.js' }, './other': { types: './t.d.ts' } },
      engines: { node: '>=22', dsh: '>=0.2' },
    }))
    writeFileSync(join(synth, 'packages/company-pack/cordis.patch.yml'), [
      '- id: off-row',
      '  name: "@deepseek-ai/dsh-off"',
      '  disabled: true',
      '- id: on-row',
      '  name: "@deepseek-ai/dsh-on"',
      '- insert:',
      '    - id: grp',
      '      name: cordis:group',
      '      group: true',
      '      config:',
      '        - id: inner',
      '          name: "@deepseek-ai/dsh-inner"',
      '    - id: dis-ins',
      '      name: "@deepseek-ai/dsh-dis"',
      '      disabled: true',
    ].join('\n'))
    writeFileSync(join(synth, 'packages/company-pack/presets/alpha/agent.cordis.yml'), [
      '- insert:',
      '    - id: preset-alpha',
      '      name: "@deepseek-ai/dsh-agent-preset"',
      '      config:',
      '        id: alpha',
      '        name: Alpha',
      '        plugins:',
      '          - id: tool-fs',
      '            name: "@deepseek-ai/dsh-tool-fs"',
    ].join('\n'))

    const cat = scanPackageCatalog(synth)
    expect(cat.presets).toHaveLength(1)
    expect(cat.presets[0]?.hasPersona).toBe(false)
    expect(cat.presets[0]?.skills).toEqual([])
    expect(cat.bundleRows.find(r => r.id === 'off-row')?.note).toBe('disabled')
    expect(cat.bundleRows.find(r => r.id === 'on-row')?.note).toBe('override')
    expect(cat.bundleRows.find(r => r.id === 'grp')?.note).toBe('cordis:group')
    expect(cat.bundleRows.find(r => r.id === 'dis-ins')?.note).toBe('disabled')
    const md = renderPackageCatalog(cat)
    expect(md).toContain('| `alpha` | Alpha | — | — | `dsh-tool-fs` |')

    // 无 presets 目录时平稳返回空数组
    const noPresets = join(tmpRoot, 'no-presets')
    mkdirSync(join(noPresets, 'packages/company-pack'), { recursive: true })
    writeFileSync(join(noPresets, 'packages/company-pack/package.json'), JSON.stringify({ name: 'np', version: '0.0.1' }))
    writeFileSync(join(noPresets, 'packages/company-pack/cordis.patch.yml'), '')
    expect(scanPackageCatalog(noPresets).presets).toEqual([])
  })
})
